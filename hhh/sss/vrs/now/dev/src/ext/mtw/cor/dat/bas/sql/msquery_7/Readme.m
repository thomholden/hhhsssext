Version 7 for MATLAB 7.0 and earlier

This directory contains Matlab m-files that provide a GUI and 
Command line interface to interact and manipulate a Microsoft 
Access97 database. 

To start the GUI version of the program simply type the following 
at the Matlab command prompt

>> msquery

The code in demo_cl.m documents how to use the command line functions.
To see a demo of the Command Line version, open demo_cl.m and modify
the opendatabase_cl function call so that the path points to an existing
Access97 database on your computer. Then type the following:

>> demo_cl



