function res = ackley(X,Y)
% Ackley's function for two input arguments x,y of same size 
res = exp(1)+20*(1-exp(-0.2*sqrt(0.5*(X.^2+Y.^2))))...
        -exp(0.5*(cos(2*pi*X)+cos(2*pi*Y)));