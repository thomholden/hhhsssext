    private void optimiseButtonActionPerformed(java.awt.event.ActionEvent evt)
    {
        doOptimisation();
    }
    
    private void doImportData()
    {
        //use the PortOptFileFilter
        fFileChooser.setFileFilter(new PortOptFileFilter());

        //show the file open dialog
        int retval = fFileChooser.showOpenDialog(this);

        if(retval == JFileChooser.APPROVE_OPTION)
        {
            File file = fFileChooser.getSelectedFile();
            try
            {
                //clear all the existing data
                clearAllData();
                setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
                fPortOptWrapper.importFile(file.getAbsolutePath());

                populateInputPanels();
                //now enable the Input and Parameters panels
                enableContents(fInputDataPanel, true);
                enableContents(fPricesPlotPanel, true);
                enableContents(fParamsPanel, true);
                
                //and make them visible
                if(!fInputDataFrame.isVisible())
                    fInputDataViewMenuItem.doClick();
                if(!fPricePlotFrame.isVisible())
                    fPricesPlotViewMenuItem.doClick();
                if(!fCovMatFrame.isVisible())
                    fCovMatViewMenuItem.doClick();
                if(!fParamsFrame.isVisible())
                    fParamViewMenuItem.doClick();
                
            }
            catch(Exception e)
            {
                System.out.println("Exception: " + e.toString());
            }
            finally
            {
                 setCursor(Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR));
            }
        }        
    }
    
    private void doOptimisation()
    {
        try
        {
            setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
            //check the parameters
            if(fParamsPanel.validateParameters())
            {
                //do the optimisation
                fPortOptWrapper.optimisePortfolio(fParamsPanel.getExpectedReturns(), fParamsPanel.getMinAssetWeights(), fParamsPanel.getMaxAssetWeights());
                populateOutputPanels();

                //now enable the output panel
                enableContents(fOutputsPanel, true);
                enableContents(fEFrontPanel, true);

                //and make them visible
                if(!fOutputsFrame.isVisible())
                    fOutputViewMenuItem.doClick();
                if(!fEFrontPlotFrame.isVisible())
                    fEFrontViewMenuItem.doClick();
            }
            else
            {
                JOptionPane.showMessageDialog(this, "Invalid stock weight limits", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
        catch(Exception e)
        {
            System.out.println("Exception: " + e.toString());
        }
        finally
        {
             setCursor(Cursor.getPredefinedCursor(Cursor.DEFAULT_CURSOR));
        }
    }
    
    private void populateInputPanels()
    {
        //Table in the Inputs tab
        fInputDataPanel.setDataStats(fPortOptWrapper.getStockNames(), fPortOptWrapper.getMeanReturns(), fPortOptWrapper.getStdReturns());
        
        fCovMatTableModel.setData(fPortOptWrapper.getStockNames(),fPortOptWrapper.getCovarianceMat());
        
        //Image in the Inputs tab
        Image im = fPortOptWrapper.getPricesImage();
        fPricesPlotPanel.setImage(im);

        //Table in the Parameters tab
        fParamsPanel.setData(fPortOptWrapper.getStockNames(), fPortOptWrapper.getMeanReturns());
    }
    
    private void populateOutputPanels()
    {
        fOutputsPanel.setData(fPortOptWrapper.getPortRisks(), fPortOptWrapper.getPortReturns(), fPortOptWrapper.getStockNames(), fPortOptWrapper.getPortWeights());
        
        Image im = fPortOptWrapper.getEfficientFrontierImage();
        fEFrontPanel.setImage(im);
    }
    
    private void clearAllData()
    {
        fInputDataPanel.clearData();
        fCovMatTableModel.clearData();
        fPricesPlotPanel.clearImage();
        fParamsPanel.clearData();
        fOutputsPanel.clearData();
        fEFrontPanel.clearImage();
        
    }

    private void enableContents(javax.swing.JComponent comp, boolean value)
    {
        java.awt.Component[] all = comp.getComponents();
        for(int i=0; i < all.length; ++i)
        {
            all[i].setEnabled(value);
        }
    }
    
    public void dispose()
    {
        //dispose of the PortOptWrapper
    	if(fPortOptWrapper != null)
    	{
    		fPortOptWrapper.dispose();
    		fPortOptWrapper = null;
    	}
        //dispose of the internal frames
    	if(fCovMatFrame != null)
    	{
    		fCovMatFrame.dispose();
    		fCovMatFrame = null;
    	}
    	if(fEFrontPlotFrame != null)
    	{
    		fEFrontPlotFrame.dispose();
    		fEFrontPlotFrame = null;
    	}
    	if(fInputDataFrame != null)
    	{
    		fInputDataFrame.dispose();
    		fInputDataFrame = null;
    	}
    	if(fOutputsFrame != null)
    	{
    		fOutputsFrame.dispose();
    		fOutputsFrame = null;
    	}
    	if(fParamsFrame != null)
    	{
    		fParamsFrame.dispose();
    		fParamsFrame = null;
    	}
        if(fPricePlotFrame != null)
    	{
        	fPricePlotFrame.dispose();
        	fPricePlotFrame= null;
    	}
        //call dispose for the base class
        super.dispose();
    }

    public void setFontSize(int size)
    {
        fEFrontPanel.setFontSize(size);
        fInputDataPanel.setFontSize(size);
        fOutputsPanel.setFontSize(size);
        fParamsPanel.setFontSize(size);
        fPricesPlotPanel.setFontSize(size);
        
        Font font = new Font("Dialog", Font.PLAIN, size);
        FontMetrics fm = getFontMetrics(font);

        fCovMatTable.setFont(font);
        fCovMatTable.setRowHeight(fm.getHeight());
        fCovMatTable.getTableHeader().setFont(font);
    }
    
