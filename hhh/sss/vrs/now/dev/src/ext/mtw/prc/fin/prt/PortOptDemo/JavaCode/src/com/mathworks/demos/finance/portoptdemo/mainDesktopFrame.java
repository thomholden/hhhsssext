    private void formWindowClosing(java.awt.event.WindowEvent evt) {//GEN-FIRST:event_formWindowClosing
        // 2007-09-18 EYMC: dispose of the PortOptWrapper before making the frame invisible.  
    	// In R2007b, making the frame invisible first causes the call to fPortOptWrapper.dispose()
    	// to hang
    	if(fPortOptWrapper != null)
    	{
    		fPortOptWrapper.dispose();
    		fPortOptWrapper = null;
    	}

        //hide the frame
        setVisible(false);
        //then dispose
        dispose();
        
    }//GEN-LAST:event_formWindowClosing

