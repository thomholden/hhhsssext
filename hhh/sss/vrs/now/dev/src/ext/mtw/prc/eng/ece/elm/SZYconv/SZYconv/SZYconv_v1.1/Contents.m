% to use: type SZYconv at the prompt
% 
% SZYconv is a quick 1-port 1-value S-parameter converter 
% it accepts graphical and text input in a variety of formats
%
% graphical input/output : 
%    - (click on) polar chart
%
% text input/output into the following formats
%
%    - GAMMAIN, RI
%    - GAMMAIN, MA, degrees
%    - GAMMAIN, MA, radians
%    - Z <ohms>
%    - Y < mS)
%    - RL, VSWR 
%
% changing one input will automatically update all fields
% for graphical input click on the chart :
% - 1st time in order to get the haircross cursor
% - 2nd time in order to actually input the data point
%
% --------
% glossary
% --------
%
% GAMMAIN  - a.k.a. S_in, S11, input reflection coefficient
%          - normalized
% MA       - magnitude & angle 
% RI       - real & imaginary
% Z        - input impedance (complex, ohms)
% Y        - input admittance (complex, mS)
% RL       - return loss (dB)
% VSWR     - voltage standing-wave ratio
%
